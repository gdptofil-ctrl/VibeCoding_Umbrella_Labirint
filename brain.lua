-- мозг. записывает все твои действия по каждому герою и учит нейросеть угадывать,
-- что ты сделаешь дальше. данные потом читаются через require("brain.core")

local core = require("brain.core")

local script = {}

local K = {
    PREDICT_EVERY = 0.2,
    FLUSH_EVERY = 30,
    SAVE_EVERY = 60,
    SAME_GAP = 0.35,
    PANEL_W = 300,
}

local ui = {}
local st = {
    hero = nil, key = nil, net = nil,
    buf = {}, bufLen = 0, records = 0,
    lastCls = 0, lastT = -10, hurtT = -99,
    nextPredict = 0, nextFlush = 0, nextSave = 0,
    probs = nil, hidden = nil, lastGuess = nil, lastReal = nil,
}
local font = nil

local function now() return GameRules.GetGameTime() end
local function on() return ui.enabled and ui.enabled:Get() end

local function buildMenu()
    local tab = Menu.Create("Scripts", "Utility", "Мозг", "Main")
    if not tab or not tab.Create then return end
    local g = tab:Create("Основное", Enum.GroupSide.Left)
    ui.enabled = g:Switch("Включить", true, "\u{f5dc}")
    ui.enabled:ToolTip("Записывает каждый твой приказ вместе с ситуацией вокруг. Для каждого героя отдельный файл.")
    ui.record = g:Switch("Записывать действия", true, "\u{f1c0}")
    ui.record:ToolTip("Данные лягут в конфиги чита, папка brain, файл с именем героя.")
    ui.learn = g:Switch("Учить нейросеть", true, "\u{f0eb}")
    ui.learn:ToolTip("После каждого приказа сеть сверяет свою догадку с тем, что ты сделал, и подправляет веса.")
    ui.panel = g:Switch("Панель", true, "\u{f2d0}")
    ui.panel:ToolTip("Догадка сети, точность и сама сеть: связи светятся по весам.")
    ui.x = g:Slider("Панель X", 0, 3000, 20, "%d")
    ui.x:ToolTip("Отступ панели слева.")
    ui.y = g:Slider("Панель Y", 0, 2000, 260, "%d")
    ui.y:ToolTip("Отступ панели сверху.")
    ui.reset = g:Button("Сбросить сеть героя", function()
        if st.key then
            core.resetNet(st.key)
            st.net = core.loadNet(st.key)
        end
    end)
    ui.reset:ToolTip("Сеть текущего героя начнёт учиться с нуля. Записанные действия не удаляются.")
end

function script.OnScriptsLoaded()
    buildMenu()
end

-- логика

local function flush()
    if st.key and #st.buf > 0 then
        core.appendChunk(st.key, table.concat(st.buf, ";"))
    end
    st.buf, st.bufLen = {}, 0
end

local function push(line)
    if not (ui.record and ui.record:Get()) or not st.key then return end
    if st.bufLen + #line + 1 > core.K.CHUNK then flush() end
    st.buf[#st.buf + 1] = line
    st.bufLen = st.bufLen + #line + 1
    st.records = st.records + 1
end

local function save()
    flush()
    if st.net and st.key then st.net:save(st.key) end
end

local function attach(hero)
    if st.hero == hero then return end
    if st.hero then save() end
    st.hero = hero
    st.key = core.heroKey(hero)
    st.net = core.loadNet(st.key)
    st.records = 0
    st.probs, st.hidden = nil, nil
end

local function fmt(v) return string.format("%.3g", v) end

local function owner(e)
    if not e or not Entity.IsEntity(e) then return nil end
    if NPC.IsHero(e) then return e end
    return NPC.GetOwnerNPC(e)
end

function script.OnUpdate()
    if not on() or not Engine.IsInGame() then return end
    local hero = Heroes.GetLocal()
    if not hero then return end
    attach(hero)

    local t = now()
    if t >= st.nextPredict and Entity.IsAlive(hero) then
        st.nextPredict = t + K.PREDICT_EVERY
        st.probs, st.hidden = st.net:forward(core.features(hero, t - st.hurtT))
    end
    if t >= st.nextFlush then st.nextFlush = t + K.FLUSH_EVERY; flush() end
    if t >= st.nextSave then st.nextSave = t + K.SAVE_EVERY; save() end
end

function script.OnPrepareUnitOrders(data)
    if type(data) ~= "table" or not on() then return true end
    if data.identifier ~= nil and data.identifier ~= "" then return true end
    local hero = Heroes.GetLocal()
    if not hero or data.npc ~= hero then return true end
    attach(hero)

    local t = now()
    local cls = core.classify(hero, data.order, data.target, data.ability)
    if cls == st.lastCls and t - st.lastT < K.SAME_GAP then return true end
    st.lastCls, st.lastT = cls, t

    local f = core.features(hero, t - st.hurtT)
    local pos = Entity.GetAbsOrigin(hero)
    local tp = data.position
    if data.target and Entity.IsEntity(data.target) then tp = Entity.GetAbsOrigin(data.target) end
    local fs = {}
    for i = 1, #f do fs[i] = fmt(f[i]) end
    push(table.concat({
        "a", fmt(GameRules.GetDOTATime()), cls, data.order or 0,
        core.abilityName(data.ability), core.targetKind(data.target),
        math.floor(pos.x), math.floor(pos.y),
        tp and math.floor(tp.x) or 0, tp and math.floor(tp.y) or 0,
        table.concat(fs, ","),
    }, ","))

    if ui.learn and ui.learn:Get() then
        st.lastGuess = st.net:train(f, cls)
        st.lastReal = cls
    end
    return true
end

function script.OnEntityHurt(data)
    if type(data) == "table" and st.hero and data.target == st.hero then st.hurtT = now() end
end

function script.OnEntityKilled(data)
    if type(data) ~= "table" or not on() or not st.hero then return end
    local target, me = data.target, st.hero
    if not target or not Entity.IsEntity(target) then return end
    local kind
    if target == me then
        kind = "death"
    elseif owner(data.source) == me then
        if NPC.IsHero(target) then kind = Entity.IsSameTeam(target, me) and "deny_hero" or "kill"
        elseif NPC.IsCreep(target) then kind = Entity.IsSameTeam(target, me) and "deny" or "lasthit"
        else kind = "destroy" end
    end
    if kind then
        push(table.concat({ "e", fmt(GameRules.GetDOTATime()), kind, NPC.GetUnitName(target) }, ","))
    end
end

function script.OnGameEnd()
    save()
    st.hero, st.key, st.net = nil, nil, nil
end

-- рисуем

local function text(size, s, x, y, col)
    Render.Text(font, size, s, Vec2(x + 1, y + 1), Color(0, 0, 0, 180))
    Render.Text(font, size, s, Vec2(x, y), col)
end

local function weightColor(w, a)
    local m = math.min(1, math.abs(w))
    if w >= 0 then return Color(90, 170, 255, math.floor(a * m)) end
    return Color(255, 90, 90, math.floor(a * m))
end

local function drawNet(x, y, w, h)
    local net = st.net
    local function col(n, cx)
        local pts, gap = {}, h / (n + 1)
        for i = 1, n do pts[i] = Vec2(cx, y + gap * i) end
        return pts
    end
    local ins, hid, outs = col(net.nin, x), col(net.nh, x + w / 2), col(net.nout, x + w)
    for j = 1, net.nh do
        for i = 1, net.nin do
            local wt = net.w1[j][i]
            Render.Line(ins[i], hid[j], weightColor(wt, 200), 1 + math.min(2, math.abs(wt)))
        end
    end
    for k = 1, net.nout do
        for j = 1, net.nh do
            local wt = net.w2[k][j]
            Render.Line(hid[j], outs[k], weightColor(wt, 200), 1 + math.min(2, math.abs(wt)))
        end
    end
    for j = 1, net.nh do
        local a = st.hidden and st.hidden[j] or 0
        local c = a >= 0 and Color(90, 170, 255, 255) or Color(255, 90, 90, 255)
        Render.FilledRect(hid[j] - Vec2(3, 3), hid[j] + Vec2(3, 3), c, 3)
    end
    for i = 1, net.nin do Render.FilledRect(ins[i] - Vec2(2, 2), ins[i] + Vec2(2, 2), Color(220, 220, 220, 255), 2) end
    for k = 1, net.nout do
        local p = st.probs and st.probs[k] or 0
        Render.FilledRect(outs[k] - Vec2(3, 3), outs[k] + Vec2(3, 3), Color(255, 255, 255, math.floor(60 + 195 * p)), 3)
    end
end

function script.OnDraw()
    if not on() or not (ui.panel and ui.panel:Get()) or not st.net then return end
    if not font then font = Render.LoadFont("MuseoSansEx", Enum.FontCreate.FONTFLAG_ANTIALIAS, 600) end
    local x, y, w = ui.x:Get(), ui.y:Get(), K.PANEL_W
    Render.FilledRect(Vec2(x, y), Vec2(x + w, y + 330), Color(14, 16, 22, 215), 8)

    local white, dim = Color(240, 240, 240, 255), Color(160, 165, 175, 255)
    text(16, "Мозг: " .. (st.key or "?"), x + 12, y + 10, white)
    local net = st.net
    local total = net.seen > 0 and net.hit / net.seen or 0
    text(13, string.format("действий: %d   за игру: %d", net.seen, st.records), x + 12, y + 32, dim)
    text(13, string.format("точность: %d%% сейчас, %d%% всего", math.floor(net.acc * 100 + 0.5),
        math.floor(total * 100 + 0.5)), x + 12, y + 48, dim)

    local yy = y + 72
    if st.probs then
        local order = {}
        for k = 1, #st.probs do order[k] = k end
        table.sort(order, function(a, b) return st.probs[a] > st.probs[b] end)
        for r = 1, 3 do
            local k = order[r]
            local p = st.probs[k]
            Render.FilledRect(Vec2(x + 12, yy), Vec2(x + 12 + (w - 24) * p, yy + 16), Color(90, 170, 255, 90), 4)
            text(13, string.format("%s  %d%%", core.CLASSES[k], math.floor(p * 100 + 0.5)), x + 18, yy + 1, white)
            yy = yy + 20
        end
    end
    if st.lastReal then
        local ok = st.lastGuess == st.lastReal
        text(12, "ты: " .. core.CLASSES[st.lastReal] .. (ok and "  угадал" or "  ждал: " .. core.CLASSES[st.lastGuess]),
            x + 12, yy + 2, ok and Color(120, 220, 120, 255) or Color(255, 150, 120, 255))
    end
    drawNet(x + 30, y + 150, w - 60, 175)
end

return script

