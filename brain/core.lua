local cfgOk = nil

function M.cfg(heroKey)
    if cfgOk == nil then
        Config.WriteString(K.DIR .. "_probe", "ok", "1")
        cfgOk = Config.ReadString(K.DIR .. "_probe", "ok", "") == "1"
    end
    return (cfgOk and K.DIR or K.FALLBACK) .. heroKey
end

local function writeLong(cfg, key, s)
    local n = 0
    for i = 1, #s, K.CHUNK do
        n = n + 1
        Config.WriteString(cfg, key .. "_" .. n, s:sub(i, i + K.CHUNK - 1))
    end
    Config.WriteInt(cfg, key .. "_n", n)
end

local function readLong(cfg, key)
    local n = Config.ReadInt(cfg, key .. "_n", 0)
    local parts = {}
    for i = 1, n do parts[i] = Config.ReadString(cfg, key .. "_" .. i, "") end
    return table.concat(parts)
end

function M.appendChunk(heroKey, s)
    local cfg = M.cfg(heroKey)
    local head = Config.ReadInt(cfg, "head", 0) % K.MAX_CHUNKS + 1
    Config.WriteString(cfg, "c" .. head, s)
    Config.WriteInt(cfg, "head", head)
    Config.WriteInt(cfg, "chunks", math.min(K.MAX_CHUNKS, Config.ReadInt(cfg, "chunks", 0) + 1))
    Config.WriteString(cfg, "columns", M.COLUMNS)
end

local function parseLine(line)
    local f = {}
    for v in (line .. ","):gmatch("([^,]*),") do f[#f + 1] = v end
    if f[1] == "a" then
        local r = { kind = "a", t = tonumber(f[2]), cls = tonumber(f[3]), order = tonumber(f[4]),
            ability = f[5], target = f[6], px = tonumber(f[7]), py = tonumber(f[8]),
            tx = tonumber(f[9]), ty = tonumber(f[10]), f = {} }
        for i = 1, #M.FEATURES do r.f[i] = tonumber(f[10 + i]) or 0 end
        return r
    elseif f[1] == "e" then
        return { kind = "e", t = tonumber(f[2]), event = f[3], name = f[4] }
    end
end

function M.read(heroKey)
    local cfg = M.cfg(heroKey)
    local total, head = Config.ReadInt(cfg, "chunks", 0), Config.ReadInt(cfg, "head", 0)
    local out = {}
    for i = 1, total do
        local idx = (head - total + i - 1) % K.MAX_CHUNKS + 1
        for line in Config.ReadString(cfg, "c" .. idx, ""):gmatch("[^;]+") do
            local r = parseLine(line)
            if r then out[#out + 1] = r end
        end
    end
    return out
end

-- нейросеть

local Net = {}
Net.__index = Net
M.Net = Net

function Net.new(nin, nh, nout)
    local n = setmetatable({ nin = nin, nh = nh, nout = nout, w1 = {}, b1 = {}, w2 = {}, b2 = {},
        seen = 0, hit = 0, acc = 0 }, Net)
    local s1, s2 = 1 / math.sqrt(nin), 1 / math.sqrt(nh)
    for j = 1, nh do
        n.b1[j] = 0
        n.w1[j] = {}
        for i = 1, nin do n.w1[j][i] = (math.random() * 2 - 1) * s1 end
    end
    for k = 1, nout do
        n.b2[k] = 0
        n.w2[k] = {}
        for j = 1, nh do n.w2[k][j] = (math.random() * 2 - 1) * s2 end
    end
    return n
end

function Net:forward(x)
    local h, p = {}, {}
    for j = 1, self.nh do
        local s, w = self.b1[j], self.w1[j]
        for i = 1, self.nin do s = s + w[i] * x[i] end
        s = clamp(s, -15, 15)
        local e = math.exp(2 * s)
        h[j] = (e - 1) / (e + 1)
    end
    local top = -math.huge
    for k = 1, self.nout do
        local s, w = self.b2[k], self.w2[k]
        for j = 1, self.nh do s = s + w[j] * h[j] end
        p[k] = s
        if s > top then top = s end
    end
    local sum = 0
    for k = 1, self.nout do p[k] = math.exp(p[k] - top); sum = sum + p[k] end
    for k = 1, self.nout do p[k] = p[k] / sum end
    return p, h
end

function Net:best(p)
    local bk, bv = 1, -1
    for k = 1, #p do if p[k] > bv then bk, bv = k, p[k] end end
    return bk, bv
end

function Net:train(x, y, lr)
    lr = lr or K.LR
    local p, h = self:forward(x)
    local guess = self:best(p)
    self.seen = self.seen + 1
    if guess == y then self.hit = self.hit + 1 end
    self.acc = self.acc + ((guess == y and 1 or 0) - self.acc) * 0.02

    local dh = {}
    for j = 1, self.nh do dh[j] = 0 end
    for k = 1, self.nout do
        local d = p[k] - (k == y and 1 or 0)
        local w = self.w2[k]
        for j = 1, self.nh do
            dh[j] = dh[j] + d * w[j]
            w[j] = w[j] - lr * d * h[j]
        end
        self.b2[k] = self.b2[k] - lr * d
    end
    for j = 1, self.nh do
        local d = dh[j] * (1 - h[j] * h[j])
        local w = self.w1[j]
        for i = 1, self.nin do w[i] = w[i] - lr * d * x[i] end
        self.b1[j] = self.b1[j] - lr * d
    end
    return guess, p
end

function Net:save(heroKey)
    local cfg = M.cfg(heroKey)
    local t = {}
    for j = 1, self.nh do for i = 1, self.nin do t[#t + 1] = string.format("%.4g", self.w1[j][i]) end end
    for j = 1, self.nh do t[#t + 1] = string.format("%.4g", self.b1[j]) end
    for k = 1, self.nout do for j = 1, self.nh do t[#t + 1] = string.format("%.4g", self.w2[k][j]) end end
    for k = 1, self.nout do t[#t + 1] = string.format("%.4g", self.b2[k]) end
    writeLong(cfg, "net", table.concat(t, ","))
    Config.WriteString(cfg, "net_shape", self.nin .. "," .. self.nh .. "," .. self.nout)
    Config.WriteInt(cfg, "seen", self.seen)
    Config.WriteInt(cfg, "hit", self.hit)
    Config.WriteFloat(cfg, "acc", self.acc)
end

function M.loadNet(heroKey)
    local cfg = M.cfg(heroKey)
    local nin, nh, nout = #M.FEATURES, K.HIDDEN, #M.CLASSES
    local n = Net.new(nin, nh, nout)
    if Config.ReadString(cfg, "net_shape", "") ~= nin .. "," .. nh .. "," .. nout then return n end
    local v = {}
    for s in readLong(cfg, "net"):gmatch("[^,]+") do v[#v + 1] = tonumber(s) or 0 end
    if #v ~= nh * nin + nh + nout * nh + nout then return n end
    local c = 0
    local function nxt() c = c + 1; return v[c] end
    for j = 1, nh do for i = 1, nin do n.w1[j][i] = nxt() end end
    for j = 1, nh do n.b1[j] = nxt() end
    for k = 1, nout do for j = 1, nh do n.w2[k][j] = nxt() end end
    for k = 1, nout do n.b2[k] = nxt() end
    n.seen = Config.ReadInt(cfg, "seen", 0)
    n.hit = Config.ReadInt(cfg, "hit", 0)
    n.acc = Config.ReadFloat(cfg, "acc", 0)
    return n
end

function M.resetNet(heroKey)
    local cfg = M.cfg(heroKey)
    Config.WriteString(cfg, "net_shape", "")
    Config.WriteInt(cfg, "seen", 0)
    Config.WriteInt(cfg, "hit", 0)
    Config.WriteFloat(cfg, "acc", 0)
end

