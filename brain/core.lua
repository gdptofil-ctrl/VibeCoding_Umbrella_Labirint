-- ядро мозга: признаки, нейросеть, хранилище. скрипты подключают через require("brain.core")

local M = {}

local K = {
    DIR = "brain/",
    FALLBACK = "brain_",
    CHUNK = 1500,
    MAX_CHUNKS = 400,
    HIDDEN = 16,
    LR = 0.05,
    NEAR = 1200,
    CREEPS = 800,
    TOWER = 900,
}
M.K = K

M.FEATURES = {
    "hp", "mana", "level", "time",
    "enemy_heroes", "ally_heroes", "enemy_creeps", "enemy_dist",
    "weak_creep", "ready_spells", "enemy_tower", "hurt",
}

M.CLASSES = {
    "движение", "атака героя", "атака крипа", "атака здания", "атака с ходу",
    "скилл 1", "скилл 2", "скилл 3", "скилл 4", "скилл 5", "скилл 6",
    "предмет", "стоп", "другое",
}

M.COLUMNS = "a,t,cls,order,ability,target,px,py,tx,ty," .. table.concat(M.FEATURES, ",")
M.EVENTS = "e,t,kind,name"

local O = Enum.UnitOrder
local MOVES = {
    [O.DOTA_UNIT_ORDER_MOVE_TO_POSITION] = true,
    [O.DOTA_UNIT_ORDER_MOVE_TO_TARGET] = true,
    [O.DOTA_UNIT_ORDER_MOVE_TO_DIRECTION] = true,
}
local CASTS = {
    [O.DOTA_UNIT_ORDER_CAST_POSITION] = true,
    [O.DOTA_UNIT_ORDER_CAST_TARGET] = true,
    [O.DOTA_UNIT_ORDER_CAST_TARGET_TREE] = true,
    [O.DOTA_UNIT_ORDER_CAST_NO_TARGET] = true,
    [O.DOTA_UNIT_ORDER_CAST_TOGGLE] = true,
    [O.DOTA_UNIT_ORDER_VECTOR_TARGET_POSITION] = true,
}

local function clamp(v, a, b) return v < a and a or (v > b and b or v) end

function M.heroKey(hero)
    local name = hero and NPC.GetUnitName(hero) or ""
    return (name:gsub("^npc_dota_hero_", ""))
end

local function isEntity(e) return e ~= nil and Entity.IsEntity(e) end

function M.targetKind(target)
    if not isEntity(target) then return "-" end
    if NPC.IsHero(target) then return "h" end
    if NPC.IsStructure(target) then return "b" end
    if NPC.IsCreep(target) then return NPC.IsLaneCreep(target) and "c" or "n" end
    return "u"
end

function M.abilityName(ab)
    if not ab then return "-" end
    local n = Ability.GetName(ab)
    return (n == nil or n == "") and "-" or n
end

function M.classify(hero, order, target, ab)
    if MOVES[order] then return 1 end
    if order == O.DOTA_UNIT_ORDER_ATTACK_MOVE then return 5 end
    if order == O.DOTA_UNIT_ORDER_ATTACK_TARGET then
        local k = M.targetKind(target)
        if k == "h" then return 2 end
        if k == "b" then return 4 end
        return 3
    end
    if CASTS[order] then
        local name = M.abilityName(ab)
        if name:sub(1, 5) == "item_" then return 12 end
        for i = 0, 5 do
            local a = NPC.GetAbilityByIndex(hero, i)
            if a and a == ab then return 6 + i end
        end
        return 14
    end
    if order == O.DOTA_UNIT_ORDER_HOLD_POSITION or order == O.DOTA_UNIT_ORDER_STOP then return 13 end
    return 14
end

function M.features(hero, hurtAgo)
    local hp = Entity.GetHealth(hero) / math.max(1, Entity.GetMaxHealth(hero))
    local maxMana = NPC.GetMaxMana(hero)
    local mana = maxMana > 0 and NPC.GetMana(hero) / maxMana or 0
    local pos = Entity.GetAbsOrigin(hero)

    local enemies = Entity.GetHeroesInRadius(hero, K.NEAR, Enum.TeamType.TEAM_ENEMY, true, true) or {}
    local allies = Entity.GetHeroesInRadius(hero, K.NEAR, Enum.TeamType.TEAM_FRIEND, true, true) or {}
    local nearest = K.NEAR + 300
    for _, e in ipairs(enemies) do
        local d = (Entity.GetAbsOrigin(e) - pos):Length2D()
        if d < nearest then nearest = d end
    end

    local creeps, weak = 0, 1
    for _, u in ipairs(Entity.GetUnitsInRadius(hero, K.CREEPS, Enum.TeamType.TEAM_ENEMY, true, true) or {}) do
        if NPC.IsCreep(u) and not NPC.IsHero(u) then
            creeps = creeps + 1
            local f = Entity.GetHealth(u) / math.max(1, Entity.GetMaxHealth(u))
            if f < weak then weak = f end
        end
    end

    local ready = 0
    for i = 0, 5 do
        local a = NPC.GetAbilityByIndex(hero, i)
        if a and Ability.GetLevel(a) > 0 and not Ability.IsPassive(a) and Ability.IsReady(a) then
            ready = ready + 1
        end
    end

    local towers = Towers.InRadius(pos, K.TOWER, Entity.GetTeamNum(hero), Enum.TeamType.TEAM_ENEMY) or {}

    return {
        hp, mana,
        clamp(NPC.GetCurrentLevel(hero) / 30, 0, 1),
        clamp(GameRules.GetDOTATime() / 3600, 0, 1),
        clamp(#enemies / 5, 0, 1),
        clamp((#allies - 1) / 4, 0, 1),
        clamp(creeps / 10, 0, 1),
        clamp(nearest / (K.NEAR + 300), 0, 1),
        weak,
        clamp(ready / 4, 0, 1),
        #towers > 0 and 1 or 0,
        (hurtAgo or 99) < 2 and 1 or 0,
    }
end

