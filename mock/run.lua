local function trimTrace(trace)
    local lines = {}
    for line in trace:gmatch("[^\n]+") do
        local l = line:gsub("^%s+", "")
        if l ~= "stack traceback:"
            and not mock.isMockFile(l)
            and not l:find("^%[C%]")
            and not l:find("in function 'xpcall'")
            and not l:find("%(%.%.%.tail calls%.%.%.%)")
        then
            l = l:gsub("^[^:]-[/\\]([^/\\:]+%.lua:)", "%1")
            table.insert(lines, l)
        end
    end
    return lines
end

local function recordError(callback, err)
    local msg = err.msg:gsub("^[^:]-[/\\]([^/\\:]+%.lua:)", "%1")
    local entry = errors[msg]
    if entry then
        entry.count = entry.count + 1
        return
    end
    entry = { msg = msg, callback = callback, count = 1, tick = world.tick, trace = trimTrace(err.trace) }
    errors[msg] = entry
    table.insert(errorOrder, entry)
end

local function handler(e) return { msg = tostring(e), trace = debug.traceback("", 2) } end

local function guarded(name, fn, ...)
    local started = os.clock()
    local result = table.pack(xpcall(fn, handler, ...))
    local spent = (os.clock() - started) * 1000

    local t = timing[name] or { calls = 0, total = 0, peak = 0 }
    timing[name] = t
    t.calls, t.total, t.peak = t.calls + 1, t.total + spent, math.max(t.peak, spent)

    if not result[1] then
        recordError(name, result[2])
        return false
    end
    return true, table.unpack(result, 2, result.n)
end

