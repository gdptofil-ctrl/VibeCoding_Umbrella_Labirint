local function out(...)
    local parts = {}
    for i = 1, select("#", ...) do parts[#parts + 1] = tostring((select(i, ...))) end
    io.write(table.concat(parts, ""), "\n")
end

local function fmt(...) return string.format(...) end

local CP1251_HIGH = {
    [0xA8] = 0x0401, [0xB8] = 0x0451,
}

local function fixEncoding(s)
    if s == nil or utf8.len(s) then return s end
    local parts = {}
    for i = 1, #s do
        local b = s:byte(i)
        if b < 0x80 then
            parts[#parts + 1] = string.char(b)
        elseif b >= 0xC0 then
            parts[#parts + 1] = utf8.char(0x0410 + (b - 0xC0))
        elseif CP1251_HIGH[b] then
            parts[#parts + 1] = utf8.char(CP1251_HIGH[b])
        else
            parts[#parts + 1] = "?"
        end
    end
    return table.concat(parts)
end

local function pad(s, width)
    s = tostring(s)
    local n = utf8.len(s) or #s
    if n >= width then return s end
    return s .. string.rep(" ", width - n)
end

local args = { ticks = 300, tps = 30, press = {}, hold = {}, set = {}, brief = false, echo = false }
local positional = {}

do
    local i = 1
    while i <= #arg do
        local a = arg[i]
        local function value() i = i + 1; return arg[i] end

        if a == "--ticks" then args.ticks = tonumber(value()); args.ticksGiven = true
        elseif a == "--tps" then args.tps = tonumber(value())
        elseif a == "--press" then
            local v = value()
            local t, label = v:match("^(%d+):(.+)$")
            if not t then out("--press ждёт ТИК:Имя, получено: ", v); os.exit(2) end
            table.insert(args.press, { tick = tonumber(t), label = fixEncoding(label) })
        elseif a == "--hold" then
            local v = value()
            local from, to, label = v:match("^(%d+)%-(%d+):(.+)$")
            if not from then out("--hold ждёт ОТ-ДО:Имя, получено: ", v); os.exit(2) end
            table.insert(args.hold, { from = tonumber(from), to = tonumber(to), label = fixEncoding(label) })
        elseif a == "--set" then
            local v = value()
            local label, raw = v:match("^(.-)=(.*)$")
            if not label then out("--set ждёт Имя=значение, получено: ", v); os.exit(2) end
            table.insert(args.set, { label = fixEncoding(label), raw = fixEncoding(raw) })
        elseif a == "--cursor" then
            local x, y = value():match("^(-?[%d.]+),(-?[%d.]+)$")
            args.cursor = { tonumber(x), tonumber(y) }
        elseif a == "--scenario" then args.scenario = value()
        elseif a == "--echo" then args.echo = true
        elseif a == "--brief" then args.brief = true
        elseif a == "--keep-going" then args.keepGoing = true
        elseif a == "-h" or a == "--help" then
            out("usage: lua mock/run.lua <script.lua> [--ticks N] [--press T:Label] [--hold A-B:Label]")
            out("       [--set Label=value] [--cursor X,Y] [--scenario file.lua] [--echo] [--brief] [--keep-going]")
            os.exit(0)
        else
            table.insert(positional, a)
        end
        i = i + 1
    end
end

