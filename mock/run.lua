local function resolve(label, class)
    local exact = {}
    for _, n in ipairs(mock.nodes[label] or {}) do
        if (class == nil and not CONTAINERS[n.class]) or n.class == class then table.insert(exact, n) end
    end
    if #exact > 0 then return exact end

    local ofClass = {}
    for _, w in ipairs(diag.widgets) do
        if class == nil or w.class == class then table.insert(ofClass, w) end
    end

    local index = tonumber(label:match("^#(%d+)$"))
    if index then
        local w = ofClass[index]
        return w and resolve(w.name, class) or {}
    end

    local hits, names = {}, {}
    for _, w in ipairs(ofClass) do
        if tostring(w.name):find(label, 1, true) and not names[w.name] then
            names[w.name] = true
            table.insert(hits, w.name)
        end
    end
    if #hits == 1 then return resolve(hits[1], class) end

    return {}
end

local function labelsOf(class)
    local names = {}
    for i, w in ipairs(diag.widgets) do
        if class == nil or w.class == class then table.insert(names, "#" .. #names + 1 .. " «" .. tostring(w.name) .. "»") end
    end
    return #names > 0 and table.concat(names, ", ") or "нет ни одного"
end

