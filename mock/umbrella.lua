local function editDistance(a, b)
    a, b = a:lower(), b:lower()
    local la, lb = #a, #b
    if la == 0 then return lb end
    if lb == 0 then return la end
    local previous = {}
    for j = 0, lb do previous[j] = j end
    for i = 1, la do
        local current = { [0] = i }
        local ca = a:byte(i)
        for j = 1, lb do
            local cost = (ca == b:byte(j)) and 0 or 1
            current[j] = min(previous[j] + 1, current[j - 1] + 1, previous[j - 1] + cost)
        end
        previous = current
    end
    return previous[lb]
end

local function documented(qualified)
    local ns, fn = qualified:match("^([%w_]+)%.([%w_]+)$")
    if ns then return surface.functions[ns] ~= nil and surface.functions[ns][fn] ~= nil end
    local cls, method = qualified:match("^([%w_]+):([%w_]+)$")
    if cls then return surface.methods[cls] ~= nil and surface.methods[cls][method] ~= nil end
    return false
end

local function suggestEnum(group, key)
    if group == nil then
        local best, bestScore = nil, huge
        for name in pairs(surface.enums) do
            local score = editDistance(key, name)
            if score < bestScore then best, bestScore = name, score end
        end
        return bestScore <= max(2, math.floor(#key / 4)) and ("Enum." .. best) or nil
    end

    local values = surface.enums[group]
    if values == nil then return nil end

    local prefixed = {}
    for name in pairs(values) do
        if name:sub(1, #key) == key then insert(prefixed, name) end
    end
    if #prefixed > 0 then
        sort(prefixed)
        return table.concat(prefixed, " / ", 1, min(#prefixed, 5))
    end

    local best, bestScore = nil, huge
    for name in pairs(values) do
        local score = editDistance(key, name)
        if score < bestScore then best, bestScore = name, score end
    end
    return bestScore <= max(2, math.floor(#key / 4)) and best or nil
end

local function suggest(owner, key)
    if owner == "Enum" then return suggestEnum(nil, key) end
    local group = owner:match("^Enum%.(.+)$")
    if group then return suggestEnum(group, key) end

    local isClass = owner:sub(1, 1) == ":"
    local name    = isClass and owner:sub(2) or owner
    local joiner  = isClass and ":" or "."
    local full    = name .. joiner .. key

    local invented = INVENTED[full]
    if invented and documented(invented) then return invented end

    local elsewhere = {}
    if not isClass then
        for ns, fns in pairs(surface.functions) do
            if fns[key] then insert(elsewhere, ns .. "." .. key) end
        end
    else
        for cls, fns in pairs(surface.methods) do
            if fns[key] then insert(elsewhere, cls .. ":" .. key) end
        end
    end
    if #elsewhere > 0 then
        sort(elsewhere)
        return table.concat(elsewhere, " / ", 1, min(#elsewhere, 3))
    end

    local own = isClass and surface.methods[name] or surface.functions[name]
    local best, bestScore = nil, huge
    local limit = max(2, math.floor(#key / 4))

    if own then
        for candidate in pairs(own) do
            local score = editDistance(key, candidate)
            if score < bestScore then best, bestScore = name .. joiner .. candidate, score end
        end
        if bestScore <= limit then return best end
    end

    best, bestScore = nil, huge
    local pool = isClass and surface.methods or surface.functions
    local j = isClass and ":" or "."
    for ns, fns in pairs(pool) do
        for candidate in pairs(fns) do
            local score = editDistance(key, candidate)
            if score < bestScore then best, bestScore = ns .. j .. candidate, score end
        end
    end
    if bestScore <= limit then return best end

    return nil
end

