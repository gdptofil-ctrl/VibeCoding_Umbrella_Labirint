local function unknown(owner, key)
    local isClass = owner:sub(1, 1) == ":"
    local full = isClass and (owner:sub(2) .. ":" .. key) or (owner .. "." .. key)

    local entry = diag.unknown[full]
    if entry then
        entry.count = entry.count + 1
        return
    end

    diag.unknown[full] = { key = full, count = 1, site = site(), hint = suggest(owner, key) }
end

local ARITY_OVERRIDE = {
    ["Menu.Create"] = { 1, 5 },

    ["Menu.Find"] = { 1, 8 },
}

local function checkArity(full, spec, got)
    local override = ARITY_OVERRIDE[full]
    local lo = override and override[1] or spec[1]
    local hi = override and override[2] or spec[2]

    if got >= lo and got <= hi then return end

    local key = full .. "|" .. got
    local entry = diag.arity[key]
    if entry then
        entry.count = entry.count + 1
    else
        diag.arity[key] = { key = full, got = got, sig = spec[4] or full, count = 1, site = site() }
    end
end

local placeholderFactories = {}

local function placeholder(returns)
    returns = returns or "nil"

    local results = {}
    for part in (returns .. ","):gmatch("([^,]*),") do
        local first = part:match("^%s*([^|]-)%s*|") or part:match("^%s*(.-)%s*$")
        local nullable = part:find("|%s*nil") ~= nil

        local value = nil
        if not nullable then
            if first == "boolean" then value = false
            elseif first == "number" or first == "integer" then value = 0
            elseif first == "string" then value = ""
            elseif first:find("%[%]$") or first == "table" then value = {}
            elseif placeholderFactories[first] then value = placeholderFactories[first]()
            end
        end
        insert(results, value)
    end

    return table.unpack(results, 1, #results)
end

local Vec2, Color, Angle

local function classIndex(className, impl)
    local spec = surface.methods[className] or {}
    local cache = {}

    return function (self, key)
        local fn = cache[key]
        if fn then return fn end

        local s = spec[key]
        local body = impl[key]

        if s == nil and body == nil then
            unknown(":" .. className, key)
            if M.keepGoing then return M.noop end
            return nil
        end

        fn = function (this, ...)
            if s then checkArity(className .. ":" .. key, s, select("#", ...)) end
            if body then return body(this, ...) end
            diag.stubbed[className .. ":" .. key] = (diag.stubbed[className .. ":" .. key] or 0) + 1
            return placeholder(s[3])
        end

        cache[key] = fn
        return fn
    end
end

