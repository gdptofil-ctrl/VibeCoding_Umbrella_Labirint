    Parent  = function (self) return self.parent end,
    SetCallback = function (self, cb, force)
        insert(self.callbacks, cb)
        if force then fire(self) end
    end,
    UnsetCallback = function (self, cb)
        for i, c in ipairs(self.callbacks) do
            if c == cb then table.remove(self.callbacks, i) break end
        end
    end,
    ToolTip  = function (self, text)
        if text ~= nil then self.tooltip = text end
        return self.tooltip
    end,
    Visible  = function (self, v) if v == nil then return self.visible end self.visible = v end,
    Disabled = function (self, v) if v == nil then return self.disabled end self.disabled = v end,
    IsPressed = function (self) return world.pressed[self.name] == true end,
    IsDown    = function (self) return world.held[self.name] == true or world.pressed[self.name] == true end,
    IsToggled = function (self) return self.toggled end,
    SetToggled = function (self, v) self.toggled = v end,
    Buttons  = function (self) return self.value, 0 end,
    Update   = function (self, a, b, c)
        if self.class == "CMenuComboBox" then self.value = b or 0 else self.value = c or self.value end
    end,
}

local function methodFor(n, key)
    if key == "ColorPicker" then
        if n.class == "CMenuGroup" then return widget("CMenuColorPicker", function (c) return c end) end
        return widget("CMenuColorPickerAttachment", function (c) return c end)
    end
    return MENU_IMPL[key]
end

WidgetMT.__name = "CMenuWidget"
WidgetMT.__tostring = function (n) return string.format("<%s %q>", n.class, n.name) end

local WIDGET_FIELDS = {
    class = true, name = true, parent = true, value = true, children = true,
    callbacks = true, visible = true, disabled = true, tooltip = true, toggled = true,
}

WidgetMT.__index = function (n, key)
    if WIDGET_FIELDS[key] then return nil end

    local spec = surface.methods[n.class] or {}
    local s = spec[key]

    if s == nil then
        unknown(":" .. n.class, key)
        if M.keepGoing then return M.noop end
        return nil
    end

    local body = methodFor(n, key)

    return function (self, ...)
        checkArity(n.class .. ":" .. key, s, select("#", ...))
        if body then return body(self, ...) end
        diag.stubbed[n.class .. ":" .. key] = (diag.stubbed[n.class .. ":" .. key] or 0) + 1
        return placeholder(s[3])
    end
end

local roots = {}

IMPL.Menu = {
    Create = function (...)
        local names = { ... }
        local parent = nil
        for depth, name in ipairs(names) do
            local class = LEVELS[depth] or "CMenuGroup"
            local siblings = parent and parent.children or roots
            local existing = nil
            for _, c in ipairs(siblings) do if c.name == name then existing = c end end
            if existing == nil then
                existing = node(class, name, parent)
                if parent == nil then insert(roots, existing) end
            end
            parent = existing
        end
        return parent
    end,
    Find   = function () return nil end,
    Opened = function () return false end,
    Style  = function () return Color(120, 180, 255, 255) end,
}

