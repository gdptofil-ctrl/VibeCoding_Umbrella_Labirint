        return realOpen(path, mode)
    end

    return world
end

local function stepToward(e, goal, dt)
    local dx, dy = goal.x - e.pos.x, goal.y - e.pos.y
    local d = sqrt(dx * dx + dy * dy)
    local stride = e.speed * dt
    if d <= stride or d < 1 then
        e.pos.x, e.pos.y = goal.x, goal.y
        return true
    end
    e.pos.x = e.pos.x + dx / d * stride
    e.pos.y = e.pos.y + dy / d * stride
    e.yaw = math.deg(atan(dy, dx))
    return false
end

local function ours(e) return isEntity(e) and world.player ~= nil and e.controller == world.player.id end

local function kill(e, src)
    e.alive, e.hp, e.order, e.attacking, e.running = false, 0, nil, false, false
    local s = world.stats
    if e == world.hero then
        s.deaths = s.deaths + 1
        if world.respawn then e.respawnAt = world.time + world.respawn end
    elseif ours(src) then
        if e.kind == "hero" and e.team ~= world.hero.team then s.kills = s.kills + 1
        elseif e.team == world.hero.team then s.denies = s.denies + 1
        else s.lasthits = s.lasthits + 1 end
    end
    if M.hooks.killed then M.hooks.killed({ source = src, target = e }) end
    if M.hooks.died then M.hooks.died(e) end
end

function M.playerOrder(spec)
    local hero = world.hero
    local kind = E_ORDER[spec.order or ""] or E_ORDER.DOTA_UNIT_ORDER_MOVE_TO_POSITION
    local ability = nil
    if spec.ability then
        for _, a in ipairs(hero.abilities) do if a.name == spec.ability then ability = a end end
        for _, a in ipairs(hero.items) do if a.name == spec.ability then ability = a end end
    end
    local target = nil
    if spec.target == "enemy" or spec.target == "creep" or spec.target == "ally_creep" then
        local kind = spec.target == "enemy" and "hero" or "creep"
        local enemy = spec.target ~= "ally_creep"
        local best = huge
        for _, e in ipairs(world.entities) do
            if e.alive and e.kind == kind and (e.team ~= hero.team) == enemy then
                local d = VectorImpl.Distance2D(e.pos, hero.pos)
                if d < best then target, best = e, d end
            end
        end
    end
    local pos = spec.pos and Vec3(spec.pos[1], spec.pos[2], 128) or (target and posOf(target)) or posOf(hero)
    issue("игрок", world.player, kind, target, pos, ability, E_ISSUER.DOTA_ORDER_ISSUER_PASSED_UNIT_ONLY, hero, false, nil, nil)
end

