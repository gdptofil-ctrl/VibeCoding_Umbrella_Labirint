        if ns:match("^%l") then
            if package.loaded[ns] == nil then package.loaded[ns] = namespace(ns, IMPL[ns]) end
        elseif _G[ns] == nil or installed[ns] then
            publish(ns, namespace(ns, IMPL[ns]))
        end
