function M.step()
    local dt = world.dt
    world.time = world.time + dt

    local hero = world.hero
    if hero and not hero.alive and hero.respawnAt and world.time >= hero.respawnAt then
        hero.alive, hero.hp, hero.respawnAt = true, hero.maxHp, nil
        hero.pos = Vec3(world.spawnPos.x, world.spawnPos.y, world.spawnPos.z)
    end

    for _, e in ipairs(world.entities) do
        if e.aggro and e.alive and e.order == nil and hero and hero.alive then
            e.order = { kind = E_ORDER.DOTA_UNIT_ORDER_ATTACK_TARGET, target = hero }
        end
    end

    if hero and hero.alive and #world.heroPath > 0 and (hero.order == nil or hero.order.path) then
        local leg = world.heroPath[world.pathLeg]
        if leg then
            hero.order = { kind = E_ORDER.DOTA_UNIT_ORDER_MOVE_TO_POSITION, position = Vec3(leg[1], leg[2], 128), path = true }
        end
    end

    for _, e in ipairs(world.entities) do
        if e.alive and e.order then
            local o = e.order
            local kind = o.kind

            if kind == E_ORDER.DOTA_UNIT_ORDER_MOVE_TO_POSITION or kind == E_ORDER.DOTA_UNIT_ORDER_ATTACK_MOVE then
                e.attacking = false
                if isVector(o.position) then
                    e.running = true
                    if stepToward(e, o.position, dt) then
                        e.running = false
                        e.order = nil
                        if o.path then world.pathLeg = world.pathLeg + 1 end
                    end
                else
                    e.order = nil
                end
            elseif kind == E_ORDER.DOTA_UNIT_ORDER_MOVE_TO_TARGET then
                if isEntity(o.target) and o.target.alive then
                    e.running = not stepToward(e, o.target.pos, dt)
                else
                    e.order, e.running = nil, false
                end
            elseif kind == E_ORDER.DOTA_UNIT_ORDER_ATTACK_TARGET then
                local t = o.target
                if not isEntity(t) or not t.alive then
                    e.order, e.attacking, e.running, e.swingLands = nil, false, false, nil
                else
                    local reach = e.range + e.hull + t.hull
                    if VectorImpl.Distance2D(e.pos, t.pos) > reach then
                        e.attacking = false
                        e.running = true
                        stepToward(e, t.pos, dt)
                    else
                        e.running = false
                        e.attacking = true

                        if e.swingLands == nil and world.time >= e.nextAttack then
                            local point = e.animPoint / max(0.2, e.attackSpeed)
                            e.swingLands = world.time + point
                            e.nextAttack = world.time + e.bat / max(0.2, e.attackSpeed)

                            local s = diag.swings[e.index] or { started = 0, landed = 0, cancelled = 0 }
                            diag.swings[e.index] = s
                            s.started = s.started + 1

                            if M.hooks.animation then
                                M.hooks.animation({
                                    unit = e, castpoint = point, lag_compensation_time = 0,
                                    playbackRate = 1, sequenceName = "attack", activity = 0,
                                    sequence = 0, sequenceVariant = 0, type = 0,
                                })
                            end
                        end

                        if e.swingLands ~= nil and world.time >= e.swingLands then
                            e.swingLands = nil
                            local s = diag.swings[e.index]
                            if s then s.landed = s.landed + 1 end
                            t.hp = t.hp - e.damage
                            if ours(e) and t.kind == "hero" and t.team ~= world.hero.team then
                                world.stats.heroDamage = world.stats.heroDamage + e.damage
                            end
                            if M.hooks.hurt then M.hooks.hurt({ source = e, target = t, damage = e.damage }) end
                            if t.hp <= 0 then kill(t, e) end
                        end
                    end
                end
            end
        elseif e.alive then
            e.running = false
            e.attacking = false
        end
    end

    world.pressed = {}
end

return M

