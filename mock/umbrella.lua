local enumName = {}

local function buildEnums()
    local root = {}

    for group, values in pairs(surface.enums) do
        local reverse = {}
        for name, value in pairs(values) do
            if reverse[value] == nil then reverse[value] = name end
        end
        enumName[group] = reverse

        root[group] = setmetatable({}, {
            __index = function (_, key)
                local v = values[key]
                if v == nil then unknown("Enum." .. group, key) end
                return v
            end,
            __pairs = function () return next, values, nil end,
        })
    end

    return setmetatable(root, {
        __index = function (_, key)
            unknown("Enum", key)
            return nil
        end,
    })
end

