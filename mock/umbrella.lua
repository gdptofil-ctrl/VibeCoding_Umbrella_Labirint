local function interrupt(unit, order)
    if unit.swingLands == nil or world.time >= unit.swingLands then return end

    local current = unit.order
    if current ~= nil
        and current.kind == E_ORDER.DOTA_UNIT_ORDER_ATTACK_TARGET
        and order.kind == E_ORDER.DOTA_UNIT_ORDER_ATTACK_TARGET
        and order.target == current.target
    then
        return
    end

    local s = diag.swings[unit.index]
    if s then s.cancelled = s.cancelled + 1 end
    unit.swingLands = nil
end

local function applyOrder(unit, order)
    local kind = order.kind

    if kind == E_ORDER.DOTA_UNIT_ORDER_MOVE_TO_POSITION
        or kind == E_ORDER.DOTA_UNIT_ORDER_ATTACK_MOVE
        or kind == E_ORDER.DOTA_UNIT_ORDER_MOVE_TO_TARGET
        or kind == E_ORDER.DOTA_UNIT_ORDER_ATTACK_TARGET
    then
        interrupt(unit, order)
        unit.order = order
        return
    end

    if kind == E_ORDER.DOTA_UNIT_ORDER_HOLD_POSITION or kind == E_ORDER.DOTA_UNIT_ORDER_STOP then
        interrupt(unit, order)
        unit.order, unit.attacking, unit.running = nil, false, false
        return
    end

    if kind == E_ORDER.DOTA_UNIT_ORDER_CAST_NO_TARGET
        or kind == E_ORDER.DOTA_UNIT_ORDER_CAST_TARGET
        or kind == E_ORDER.DOTA_UNIT_ORDER_CAST_POSITION
    then
        local ab = order.ability
        if isAbility(ab) then
            if world.time < ab.cooldownUntil then
                warn("cast-cd:" .. ab.name, "каст " .. ab.name .. " на кулдауне - сервер такой приказ проигнорирует")
            elseif unit.mana < ab.mana then
                warn("cast-mana:" .. ab.name, "каст " .. ab.name .. " без маны - сервер такой приказ проигнорирует")
            else
                unit.mana = unit.mana - ab.mana
                ab.cooldownUntil = world.time + ab.cooldown
                ab.lastUsed = world.time
            end
        end
        return
    end
end

local function issue(source, player, kind, target, position, ability, issuer, npc, queue, identifier, callback)
    local units = {}

    if issuer == E_ISSUER.DOTA_ORDER_ISSUER_SELECTED_UNITS and player then
        for _, u in ipairs(player.selected or {}) do insert(units, u) end
    elseif npc ~= nil then
        insert(units, npc)
    end

    local record = {
        tick       = world.tick,
        time       = world.time,
        source     = source,
        kind       = kind,
        name       = orderName(kind),
        target     = target,
        position   = position,
        ability    = ability,
        identifier = identifier,
        units      = units,
        site       = site(),
    }

    if kind == nil then
        warn("order-nil", "тип приказа nil - скорее всего опечатка в имени Enum.UnitOrder")
    end

    if #units == 0 then warn("order-nounit", source .. ": приказ без юнита (npc = nil)") end

    for _, u in ipairs(units) do
        if not isEntity(u) then
            warn("order-notentity", source .. ": в приказ передан не юнит (" .. type(u) .. ")")
        elseif not u.alive then
            warn("order-dead", source .. ": приказ мёртвому юниту " .. u.name)
        elseif player and u.controller ~= player.id then
            warn("order-foreign", source .. ": приказ юниту, который тебе не подконтролен (" .. u.name .. ")")
        end
    end

    if (kind == E_ORDER.DOTA_UNIT_ORDER_ATTACK_TARGET or kind == E_ORDER.DOTA_UNIT_ORDER_CAST_TARGET)
        and not isEntity(target)
    then
        warn("order-notarget", source .. ": " .. record.name .. " без цели")
    end

    if kind == E_ORDER.DOTA_UNIT_ORDER_MOVE_TO_POSITION and not isVector(position) then
        warn("order-nopos", source .. ": MOVE_TO_POSITION без позиции")
    end

    if callback ~= false and M.hooks.orders then
        local ok, allowed = M.hooks.orders({
            player      = player,
            order       = kind,
            target      = target,
            position    = position,
            ability     = ability,
            orderIssuer = issuer,
            npc         = npc,
            queue       = queue or false,
            showEffects = false,
            identifier  = identifier,
        })
        if ok and allowed == false then
            diag.blocked = diag.blocked + 1
            record.blocked = true
            insert(diag.orders, record)
            return
        end
    end

    insert(diag.orders, record)
    world.ordersThisTick = world.ordersThisTick + 1

    for _, u in ipairs(units) do
        if isEntity(u) and u.alive then
            applyOrder(u, { kind = kind, target = target, position = position, ability = ability })
        end
    end
end

local function namespace(ns, impl)
    local spec = surface.functions[ns] or {}
    local cache = {}

    return setmetatable({}, {
        __index = function (_, key)
            local fn = cache[key]
            if fn then return fn end

            local s = spec[key]

            if s == nil then
                unknown(ns, key)
                if M.keepGoing then return M.noop end
                return nil
            end

            local body = impl and impl[key]

            local full = ns .. "." .. key
            fn = function (...)
                if s then checkArity(full, s, select("#", ...)) end
                if body then
                    local r = table.pack(pcall(body, ...))
                    if not r[1] then
                        local why = tostring(r[2]):gsub("^.-:%d+: ", "")
                        error(full .. ": получила не то (" .. why .. "). Сигнатура: " .. (s[4] or full), 2)
                    end
                    return table.unpack(r, 2, r.n)
                end
                diag.stubbed[full] = (diag.stubbed[full] or 0) + 1
                return placeholder(s[3])
            end

            cache[key] = fn
            return fn
        end,
    })
end

local function inRadius(list, pos, radius, teamNum, teamType, omitIllusions, omitDormant)
    local out = {}
    for _, e in ipairs(list) do
        if e.alive
            and (not omitDormant or not e.dormant)
            and (not omitIllusions or e.kind ~= "illusion")
            and VectorImpl.Distance2D(e.pos, pos) <= radius
        then
            local ok = true
            if teamType == E_TTYPE.TEAM_FRIEND then ok = e.team == teamNum
            elseif teamType == E_TTYPE.TEAM_ENEMY then ok = e.team ~= teamNum end
            if ok then insert(out, e) end
        end
    end
    return out
end

