end

local function site()
    for level = 3, 40 do
        local info = debug.getinfo(level, "Sl")
        if info == nil then break end
        local src = info.short_src or ""
        if info.what ~= "C" and not M.isMockFile(src) and (info.currentline or 0) > 0 then
            return (src:gsub("^.*[/\\]", "")) .. ":" .. info.currentline
        end
    end
    return "?"
end

local function warn(key, text)
    local entry = diag.warnings[key]
    if entry then
        entry.count = entry.count + 1
    else
        diag.warnings[key] = { text = text, count = 1, site = site() }
    end
end

