local function merge(base, over)
    local out = {}
    for k, v in pairs(base) do out[k] = v end
    for k, v in pairs(over or {}) do out[k] = v end
    return out
end

function M.install(scenario)
    scenario = merge(DEFAULT_SCENARIO, scenario)

    world.dt       = 1 / (scenario.tps or 30)
    world.cursor   = Vec3(scenario.cursor[1], scenario.cursor[2], 128)
    world.walls    = scenario.walls or {}
    world.heroPath = scenario.heroPath or {}
    world.orderBudget = scenario.orderBudget

    local radiant = E_TNUM.TEAM_RADIANT or 2
    local dire    = E_TNUM.TEAM_DIRE or 3
    local pid     = scenario.playerId or 0

    world.player = setmetatable({ id = pid, team = radiant, selected = {} }, PlayerMT)

    local heroDef = merge(scenario.hero, { team = radiant, controller = pid, kind = "hero" })
    world.hero = spawn(heroDef)
    world.player.selected = { world.hero }

    for _, u in ipairs(scenario.units or {}) do
        spawn(merge(u, { team = radiant, controller = pid }))
    end

    world.respawn = scenario.respawn
    world.spawnPos = Vec3(world.hero.pos.x, world.hero.pos.y, world.hero.pos.z)
    world.stats = { kills = 0, deaths = 0, lasthits = 0, denies = 0, heroDamage = 0 }

    for _, e in ipairs(scenario.enemies or {}) do
        local u = spawn(merge(e, { team = e.team or dire }))
        if e.attack == "hero" then u.aggro = true end
    end

    for _, a in ipairs(scenario.allies or {}) do
        spawn(merge(a, { team = radiant }))
    end

    for name, value in pairs(scenario.globals or {}) do
        publish(name, value)
    end

    publish("__UMBRELLA_MOCK", true)
    publish("Vector", function (x, y, z) return Vec3(x, y, z) end)
    publish("Vec2", Vec2)
    publish("Color", Color)
    publish("Angle", Angle)
    publish("Enum", EnumRoot)

