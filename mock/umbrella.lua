local LEVELS = { "CFirstTab", "CTabSection", "CSecondTab", "CThirdTab", "CMenuGroup" }

local WidgetMT = {}
local nodes = {}

local function node(class, name, parent, value)
    local n = setmetatable({
        class = class, name = name, parent = parent, value = value,
        children = {}, callbacks = {}, visible = true, disabled = false,
        tooltip = "", toggled = false,
    }, WidgetMT)

    if parent then insert(parent.children, n) end

    nodes[name] = nodes[name] or {}
    insert(nodes[name], n)

    return n
end

local function fire(n)
    for _, cb in ipairs(n.callbacks) do
        local ok, err = pcall(cb, n)
        if not ok then warn("menu-cb:" .. n.name, "ошибка в колбэке виджета «" .. n.name .. "»: " .. tostring(err)) end
    end
end

local function widget(class, default)
    return function (self, name, ...)
        local value = nil
        if default then value = default(...) end
        local w = node(class, name or "?", self, value)
        insert(diag.widgets, { class = class, name = name, parent = self.name, node = w })
        return w
    end
end

local function levelBelow(n)
    for i, c in ipairs(LEVELS) do
        if c == n.class then return LEVELS[i + 1] end
    end
    return nil
end

