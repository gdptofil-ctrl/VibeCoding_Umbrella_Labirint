def parse_params(raw):
    params = []
    for piece in [p.strip() for p in raw.split(',') if p.strip()]:
        optional = piece.startswith('[') or piece.endswith(']')
        name = piece.strip('[] ')
        params.append({'name': name, 'optional': optional or name == '...'})
    return params


