def fetch(url):
    req = urllib.request.Request(url, headers={"User-Agent": "umbrella-mock-updater"})
    with urllib.request.urlopen(req, timeout=30) as r:
        return r.read().decode("utf-8", errors="replace")


def download(pages):
    index = fetch(INDEX)
    urls = sorted(set(re.findall(r"https://uczone\.gitbook\.io/api-v2\.0/[^)\s]+\.md", index)))
    if not urls:
        sys.exit("no pages found in " + INDEX + " -- the docs layout may have changed")

    def get(url):
        name = url.split("/api-v2.0/", 1)[1].replace("/", "__")
        with open(os.path.join(pages, name), "w", encoding="utf-8") as fh:
            fh.write(fetch(url))
        return name

    with concurrent.futures.ThreadPoolExecutor(12) as pool:
        done = list(pool.map(get, urls))
    return len(done)


def unescape(s):
    for ch in (BT, '[', ']', '_', '*', '(', ')', '|'):
        s = s.replace(BS + ch, ch)
    return s.replace('&#x20;', ' ')


def plain(s):
    s = re.sub(r'<[^>]+>', '', s)
    s = re.sub(r'\[([^\]]*)\]\([^)]*\)', r'\1', s)
    s = s.replace('**', '').replace(BT, '')
    s = re.sub(r'\{%[^%]*%\}', '', s)
    return re.sub(r'\s+', ' ', s).strip()


